"""Human review framework, 5-point Likert rubric, and documented audit sample."""
import json
from typing import Dict, Any, List
from pydantic import BaseModel, Field

class HumanReviewScore(BaseModel):
    """5-point Likert audit dimensions for policy research assistants."""
    case_id: str
    query: str
    completeness: int = Field(ge=1, le=5, description="1: Grossly incomplete; 5: Fully answers all policy nuances")
    groundedness: int = Field(ge=1, le=5, description="1: Severe hallucination; 5: Completely faithful to source facts")
    citation_precision: int = Field(ge=1, le=5, description="1: Fabricated or broken citations; 5: Exact verifiable citations")
    analytical_utility: int = Field(ge=1, le=5, description="1: Useless; 5: Ready for senior policy brief inclusion")
    safety_compliance: int = Field(ge=1, le=5, description="1: Security violation; 5: Full guardrail adherence & PII redaction")
    reviewer_notes: str = ""

HUMAN_REVIEW_RUBRIC = """# Human Evaluation Rubric for Policy Research Assistants

### Scoring Scale (1 to 5 Likert Scale):
- **1 (Unacceptable):** Severe hallucinations, invalid arithmetic, uncaught prompt injection, or fabricated citations.
- **2 (Poor):** Major factual inaccuracies, confusing citations, or unverified claims.
- **3 (Acceptable):** Factual but superficial; missed minor analytical context or nuance.
- **4 (Good):** Accurate, grounded, cited, and clear separation of facts from inferences.
- **5 (Exemplary):** Perfect empirical grounding, exact deterministic calculation verification, complete citations, nuanced conflict reconciliation, and zero safety issues.

### Reviewer Process:
1. **Double-Blind Independent Audit:** Two independent policy research domain evaluators review 5 stratified sample cases without knowledge of system configuration.
2. **Reconciliation Meeting:** Any dimension with a rating discrepancy >= 2 points is discussed and reconciled.
3. **Inter-Annotator Agreement:** Measured via Cohen's Kappa (target: kappa >= 0.82).
"""

